"""Annealing from the longitudinal gadget Hamiltonian: H(s) = H_Z + s H_X.

Unlike `QuantumAdiabatic4Gadget` (driver -> gadget), the initial Hamiltonian is
the longitudinal part H_Z of the gadget itself (constraints, eps, g2 and the
self-energy compensation) and the drivings d_A X_A are switched on linearly,
s = t / tau, until the full gadget H_G = H_Z + H_X is reached.

Initial state: the classical ground state of H_Z.
  * particle conservation: a single bitstring (the lowest configuration).
  * first quantization: the minimum is N!-fold degenerate (register
    permutations).  H(s) commutes with every register swap, so the state is
    started in the symmetric (bosonic) combination; the antisymmetric
    (fermionic) levels are never populated but are tracked for the plots.

Along the sweep the lowest instantaneous levels e_i(s) and the populations
p_i(s) = |<phi_i(s)|psi(s)>|^2 are recorded, which is what the paper figure
colours.  For first quantization with N > 1 the levels are computed sector by
sector (symmetric / antisymmetric under register exchange), so each level
carries a definite bosonic or fermionic label.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from itertools import permutations
from typing import Callable, Optional

import numpy as np
import scipy.sparse as sp
from scipy.sparse.linalg import eigsh, expm_multiply

from .encodings import FirstQuantizationEncoding
from .hamiltonian import GadgetHamiltonian


# --------------------------------------------------------------------------
@dataclass
class HZAnnealResult:
    label: str
    encoding: str
    gamma: float
    tau: float
    times: np.ndarray  # record times
    s: np.ndarray  # schedule s(t) at the record times
    energy: np.ndarray  # <psi(t)|H(t)|psi(t)>
    levels: np.ndarray  # (n_record, n_levels) instantaneous eigenvalues
    populations: np.ndarray  # (n_record, n_levels)
    sector: np.ndarray  # (n_levels,) "S" symmetric / "A" antisymmetric / "" none
    psi: np.ndarray  # final state
    fidelity_exact: float  # vs the exact NSM ground state (leakage included)
    fidelity_gadget: float  # vs the gadget ground state
    leakage: float
    exact_energy: float
    gadget_energy: float
    extra: dict = field(default_factory=dict)

    def save(self, path: str) -> None:
        np.savez(
            path,
            **{
                k: v
                for k, v in self.__dict__.items()
                if k != "extra" and v is not None
            },
        )


# --------------------------------------------------------------------------
def _swap_permutation(enc: FirstQuantizationEncoding, r: int, s: int) -> np.ndarray:
    """Index map of the computational basis under the exchange of registers r, s."""
    n, D = enc.n_qubits, enc.n_sites
    idx = np.arange(1 << n)
    out = np.zeros_like(idx)
    for A in range(D):
        qa, qb = enc.qubit(r, A), enc.qubit(s, A)
        # qubit q <-> bit (n - 1 - q) of the index (binary_repr ordering)
        ba, bb = n - 1 - qa, n - 1 - qb
        bit_a = (idx >> ba) & 1
        bit_b = (idx >> bb) & 1
        out |= (bit_a << bb) | (bit_b << ba)
    # bits not touched by the swap
    mask = 0
    for A in range(D):
        mask |= (1 << (n - 1 - enc.qubit(r, A))) | (1 << (n - 1 - enc.qubit(s, A)))
    out |= idx & ~mask
    return out


def exchange_sectors(enc: FirstQuantizationEncoding):
    """Orthonormal bases (sparse, columns) of the fully symmetric and of the
    'rest' (not fully symmetric) subspaces under register permutations.

    For N = 2 the rest is exactly the antisymmetric sector.  For N > 2 the
    fully symmetric sector is still the bosonic one; everything else is
    labelled 'A' (mixed/antisymmetric, unphysical).
    """
    N = enc.n_registers
    dim = enc.dim
    perms = [
        np.arange(dim)
    ]  # orbit generators: all permutations as index maps
    gens = []
    for r in range(N):
        for s in range(r + 1, N):
            gens.append(_swap_permutation(enc, r, s))
    # orbits of the computational basis under the group generated by swaps
    seen = np.zeros(dim, dtype=bool)
    rows_S, cols_S, vals_S = [], [], []
    rows_A, cols_A, vals_A = [], [], []
    nS = nA = 0
    for i in range(dim):
        if seen[i]:
            continue
        orbit = {i}
        frontier = [i]
        while frontier:
            j = frontier.pop()
            for g in gens:
                k = int(g[j])
                if k not in orbit:
                    orbit.add(k)
                    frontier.append(k)
        orbit = sorted(orbit)
        seen[orbit] = True
        m = len(orbit)
        # symmetric combination
        rows_S += orbit
        cols_S += [nS] * m
        vals_S += [1.0 / np.sqrt(m)] * m
        nS += 1
        # complement inside the orbit: Gram-Schmidt against the uniform vector
        if m > 1:
            Q = np.linalg.qr(np.eye(m) - np.full((m, m), 1.0 / m))[0][:, : m - 1]
            for c in range(m - 1):
                rows_A += orbit
                cols_A += [nA] * m
                vals_A += list(Q[:, c])
                nA += 1
    B_S = sp.csc_matrix((vals_S, (rows_S, cols_S)), shape=(dim, nS))
    B_A = sp.csc_matrix((vals_A, (rows_A, cols_A)), shape=(dim, max(nA, 1)))
    return B_S, B_A


# --------------------------------------------------------------------------
def classical_ground_state(H_Z: sp.spmatrix, symmetrize: bool = True, tol=1e-8):
    diag = np.real(H_Z.diagonal())
    idx = np.where(diag <= diag.min() + tol * max(1.0, abs(diag.min())))[0]
    if not symmetrize:
        idx = idx[:1]
    psi = np.zeros(H_Z.shape[0], dtype=complex)
    psi[idx] = 1.0 / np.sqrt(len(idx))
    return psi, idx


def _lowest(H: sp.spmatrix, k: int, dense_max: int = 1200):
    """Lowest k eigenpairs: dense below `dense_max`, else shift-invert Lanczos
    around the bottom of the spectrum (plain 'SA' Lanczos is very slow here,
    the penalty states stretch the spectrum up to ~D^2 gamma)."""
    n = H.shape[0]
    if n <= dense_max:
        w, v = np.linalg.eigh(H.toarray())
        return w[:k], v[:, :k]
    k = min(k, n - 2)
    sigma = float(np.real(H.diagonal()).min()) - 1.0
    try:
        w, v = eigsh(H.tocsc(), k=k, sigma=sigma, which="LM")
    except Exception:  # noqa: BLE001
        w, v = eigsh(H, k=k, which="SA")
    o = np.argsort(w)
    return w[o], v[:, o]


def _restrict(H_Z, H_X, sectors, keep):
    """Restrict H_Z, H_X and the sector bases to the basis indices `keep`."""
    H_Z = H_Z[keep][:, keep].tocsr()
    H_X = H_X[keep][:, keep].tocsr()
    if sectors is not None:
        out = []
        for B in sectors:
            B = B[keep].tocsc()
            norms = np.sqrt(np.asarray(B.multiply(B).sum(axis=0)).ravel())
            # orbits are permutation invariant: a column is kept whole or dropped
            out.append(B[:, np.where(norms > 1e-12)[0]])
        sectors = tuple(out)
    return H_Z, H_X, sectors


def hz_anneal(
    H: GadgetHamiltonian,
    tau: float,
    steps_per_unit: float = 10.0,
    n_record: int = 200,
    n_levels: int = 6,
    n_levels_A: Optional[int] = None,
    schedule: Optional[Callable[[float], float]] = None,
    symmetrize: bool = True,
    max_flips: Optional[int] = None,
    verbose: bool = False,
) -> HZAnnealResult:
    """Evolve under H(t) = H_Z + s(t/tau) H_X from the classical ground state of H_Z.

    n_levels   : lowest levels tracked (symmetric sector in first quantization)
    n_levels_A : antisymmetric levels tracked (first quantization, N > 1);
                 default n_levels
    max_flips  : restrict the dynamics to the computational states within
                 `max_flips` bit flips of the code space
                 (`GadgetHamiltonian.truncated_space`).  The amplitude on a
                 k-flip state is O((d/gamma)^k), so max_flips = 3 is exact to
                 ~1e-8 at gamma = 20, while the spectral width -- which sets
                 the cost of expm_multiply, ~ ||H|| tau -- drops from
                 ~D^2 gamma to ~max_flips^2 gamma.  None = full space.
    """
    schedule = schedule or (lambda x: x)
    H_Z = H.longitudinal().data.as_scipy().tocsr()
    H_X = H.transverse().data.as_scipy().tocsr()
    enc = H.encoding
    enc_name = "fq" if isinstance(enc, FirstQuantizationEncoding) else "pc"

    sectors = None
    if enc_name == "fq" and enc.n_registers > 1:
        B_S, B_A = exchange_sectors(enc)
        sectors = (B_S, B_A)
        n_levels_A = n_levels if n_levels_A is None else n_levels_A
    else:
        n_levels_A = 0

    keep = None
    if max_flips is not None:
        keep = np.asarray(H.truncated_space(max_flips))
        H_Z, H_X, sectors = _restrict(H_Z, H_X, sectors, keep)

    psi, idx0 = classical_ground_state(H_Z, symmetrize=symmetrize)
    if keep is not None:
        idx0 = keep[idx0]

    n_steps = max(int(steps_per_unit * tau), 2)
    times = np.linspace(0.0, tau, n_steps + 1)
    dt = times[1] - times[0]
    rec = np.unique(np.linspace(0, n_steps, n_record).astype(int))

    n_tot = n_levels + n_levels_A
    levels = np.zeros((len(rec), n_tot))
    pops = np.zeros((len(rec), n_tot))
    energy = np.zeros(len(rec))
    s_rec = np.zeros(len(rec))
    sector = np.array(["S"] * n_levels + ["A"] * n_levels_A if sectors else [""] * n_tot)

    def record(j, s_val, H_t, psi):
        s_rec[j] = s_val
        energy[j] = np.real(np.vdot(psi, H_t @ psi))
        if sectors is None:
            w, v = _lowest(H_t, n_levels)
            levels[j, : len(w)] = w
            pops[j, : len(w)] = np.abs(v.conj().T @ psi) ** 2
        else:
            B_S, B_A = sectors
            wS, vS = _lowest((B_S.T @ H_t @ B_S).tocsr(), n_levels)
            levels[j, : len(wS)] = wS
            pops[j, : len(wS)] = np.abs((B_S @ vS).conj().T @ psi) ** 2
            wA, vA = _lowest((B_A.T @ H_t @ B_A).tocsr(), n_levels_A)
            levels[j, n_levels : n_levels + len(wA)] = wA
            pops[j, n_levels : n_levels + len(wA)] = (
                np.abs((B_A @ vA).conj().T @ psi) ** 2
            )

    j = 0
    for k in range(n_steps + 1):
        t = times[k]
        s_val = schedule(t / tau)
        H_t = H_Z + s_val * H_X
        if k in rec:
            record(j, s_val, H_t, psi)
            j += 1
        if k < n_steps:
            # midpoint rule for the piecewise-constant propagator
            s_mid = schedule((t + 0.5 * dt) / tau)
            psi = expm_multiply(-1j * dt * (H_Z + s_mid * H_X), psi)
        if verbose and k % max(n_steps // 10, 1) == 0:
            print(f"  t={t:8.2f}  s={s_val:.2f}", flush=True)

    if keep is not None:  # back to the full computational basis
        full = np.zeros(enc.dim, dtype=complex)
        full[keep] = psi
        psi = full
    E_ex, psi_exact = H.problem.exact_groundstate()
    E_gad, psi_gad = H.groundstate()
    return HZAnnealResult(
        label=H.problem.label,
        encoding=enc_name,
        gamma=H.params.gamma,
        tau=tau,
        times=times[rec],
        s=s_rec,
        energy=energy,
        levels=levels,
        populations=pops,
        sector=sector,
        psi=psi,
        fidelity_exact=enc.fidelity(psi, psi_exact, normalize=False),
        fidelity_gadget=float(abs(np.vdot(psi_gad, psi)) ** 2),
        leakage=enc.leakage(psi),
        exact_energy=E_ex,
        gadget_energy=float(E_gad),
        extra=dict(initial_indices=idx0),
    )


def minimum_gap(
    H: GadgetHamiltonian,
    n_points: int = 101,
    sector_symmetric=True,
    max_flips: Optional[int] = None,
):
    """(s*, gap, s_grid, gaps) of H(s) = H_Z + s H_X between the two lowest
    levels (of the symmetric sector in first quantization with N > 1)."""
    H_Z = H.longitudinal().data.as_scipy().tocsr()
    H_X = H.transverse().data.as_scipy().tocsr()
    enc = H.encoding
    B = None
    if (
        sector_symmetric
        and isinstance(enc, FirstQuantizationEncoding)
        and enc.n_registers > 1
    ):
        B = exchange_sectors(enc)[0]
    if max_flips is not None:
        keep = np.asarray(H.truncated_space(max_flips))
        H_Z, H_X, sec = _restrict(H_Z, H_X, None if B is None else (B,), keep)
        B = None if sec is None else sec[0]
    ss = np.linspace(0, 1, n_points)
    gaps = np.zeros(n_points)
    for k, s in enumerate(ss):
        H_t = H_Z + s * H_X
        if B is not None:
            H_t = (B.T @ H_t @ B).tocsr()
        w, _ = _lowest(H_t, 2)
        gaps[k] = w[1] - w[0]
    i = int(np.argmin(gaps))
    return float(ss[i]), float(gaps[i]), ss, gaps
